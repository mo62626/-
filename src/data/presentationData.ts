export function filterGlossary(query: string, terms: GlossaryTerm[] = GLOSSARY_TERMS): GlossaryTerm[] {
  const q = query.trim().toLowerCase();
  if (!q) return terms;
  return terms.filter(
    (g) =>
      g.en.toLowerCase().includes(q) ||
      g.ar.toLowerCase().includes(q) ||
      g.def.toLowerCase().includes(q) ||
      g.mean.toLowerCase().includes(q)
  );
}

